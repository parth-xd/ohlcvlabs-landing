#!/usr/bin/env python3
"""Builds app-preview/index.html: the OHLCV app's lock screen, standalone.

The home page's laptop shows the real app opening. Rather than re-creating
the lock screen (and drifting from it), this copies its pieces out of the
app's own index.html word for word: the <head> colour pick, the lock CSS,
the #pin-lock markup and the intro script. Only the keypad is a dummy — it
fills the dots and clears them; nothing is sent anywhere.

    python3 tools/build_app_preview.py [path/to/Grow/index.html]

Default source: ../Grow/index.html next to this repo. Every piece is found by
a marker; if one has moved, the build stops instead of shipping half a screen.
Re-run it whenever the app's lock screen changes.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "Grow", "index.html")
OUT = os.path.join(ROOT, "app-preview", "index.html")


def between(text, start, end, name, include_end=True):
    i = text.find(start)
    if i < 0:
        sys.exit("build_app_preview: start of %s not found (%r)" % (name, start[:60]))
    j = text.find(end, i + len(start))
    if j < 0:
        sys.exit("build_app_preview: end of %s not found (%r)" % (name, end[:60]))
    return text[i:j + len(end)] if include_end else text[i:j]


def main():
    with open(SRC, encoding="utf-8") as fh:
        app = fh.read()

    head_script = between(app, "<script>\n/* Lock-screen ground", "</script>", "head colour script")
    # The lock CSS runs from its section header to the desktop rules for the
    # keypad. That last block sits inside a wider @media rule, so it is closed
    # here rather than copying the unrelated dashboard rules that follow.
    css = between(app, "  /* ── PIN Lock Screen", "    .pin-key { height: 52px; }\n", "lock CSS") + "  }\n"
    markup = between(app, '<div id="pin-lock">', "\n</div>\n\n<header>", "#pin-lock markup", include_end=False) + "\n</div>"
    intro = between(app, "// ── Lock-screen intro", "\n// Was hardcoded to 'http://localhost:8000'", "intro script", include_end=False)
    for must in ("_lockIntroTimers", "runLockIntro", "at(3750, finish)", "pin-shot"):
        if must not in css + markup + intro:
            sys.exit("build_app_preview: %r missing from the copied lock screen" % must)

    # Start hidden: runLockIntro() returns early on a hidden lock, so the intro
    # waits until the home page says the laptop is open (or plays at once when
    # this page is opened on its own).
    markup = markup.replace('<div id="pin-lock">', '<div id="pin-lock" class="hidden">', 1)

    page = PAGE.format(head_script=head_script, css=css, markup=markup, intro=intro)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(page)
    print("wrote %s (%d bytes) from %s" % (os.path.relpath(OUT, ROOT), len(page), SRC))


PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<meta name="robots" content="noindex">
<title>OHLCV</title>
<!-- GENERATED by tools/build_app_preview.py from the app's index.html.
     Do not edit by hand: change the app, then re-run the build. -->
{head_script}
<style>
  * {{ margin: 0; padding: 0; box-sizing: border-box; }}
  body {{ font-family: -apple-system, BlinkMacSystemFont, 'SF Pro Display', 'SF Pro Text', 'Helvetica Neue', sans-serif; min-height: 100vh; font-weight: 400; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale; line-height: 1.47059; letter-spacing: -.022em; font-size: 14px; overflow: hidden; }}
{css}
  /* Preview only: inside the home page's laptop, a scroll over the screen
     must carry on to the page. The app stops overscroll here for iOS
     rubber-banding, which in an iframe would trap the page's scroll. */
  #pin-lock {{ overscroll-behavior: auto; }}
  /* Preview only: the PIN typing itself on the home page. A key being
     "pressed" takes the app's own :active look; once four digits are in,
     the dots breathe while the screen waits for the visitor. */
  .pin-key.auto-press {{ background: var(--lock-ink); color: var(--lock-ground); transition-duration: 0s; }}
  @keyframes pinWait {{ 0%, 100% {{ opacity: 1; }} 50% {{ opacity: .3; }} }}
  .pin-dots.waiting .pin-dot.filled {{ animation: pinWait 1.6s ease-in-out infinite; }}
  .pin-dots.waiting .pin-dot:nth-child(2) {{ animation-delay: .12s; }}
  .pin-dots.waiting .pin-dot:nth-child(3) {{ animation-delay: .24s; }}
  .pin-dots.waiting .pin-dot:nth-child(4) {{ animation-delay: .36s; }}
  @media (prefers-reduced-motion: reduce) {{ .pin-dots.waiting .pin-dot.filled {{ animation: none; }} }}
</style>
</head>
<body class="locked">
{markup}
<script>
// Only reached when the app's palette was never painted by the <head> script.
function readLockPaletteCache() {{ return null; }}

{intro}
// ── Preview wiring (not part of the app) ────────────────────────────────
// Dummy keypad: fills the dots, then clears them. No PIN is checked or sent.
let _pin = '';
function _pinDots() {{
  for (let i = 0; i < 4; i++) document.getElementById('pd' + i).classList.toggle('filled', i < _pin.length);
}}
function pinKey(d) {{
  if (_pin.length >= 4) return;
  _pin += d; _pinDots();
  if (_pin.length === 4) setTimeout(() => {{ _pin = ''; _pinDots(); }}, 450);
}}
function pinDel() {{ _pin = _pin.slice(0, -1); _pinDots(); }}

function previewPlay() {{
  const lock = document.getElementById('pin-lock');
  lock.classList.add('no-anim');
  lock.classList.remove('hidden');
  void lock.offsetWidth;
  lock.classList.remove('no-anim');
  runLockIntro();
}}
// The PIN types itself: each key lights as it is pressed and its dot fills,
// then the dots breathe until the visitor moves on. Display only — the
// digits go nowhere.
const _autoTimers = [];
function previewAutotype() {{
  _autoTimers.splice(0).forEach(clearTimeout);
  _pin = ''; _pinDots();
  const dots = document.querySelector('.pin-dots');
  dots.classList.remove('waiting');
  const keys = [...document.querySelectorAll('.pin-key')];
  const press = d => keys.find(k => k.textContent.trim() === d);
  let t = 450;
  ['2', '7', '0', '4'].forEach(d => {{
    _autoTimers.push(setTimeout(() => {{ const k = press(d); k.classList.add('auto-press'); _pin += d; _pinDots(); }}, t));
    _autoTimers.push(setTimeout(() => press(d).classList.remove('auto-press'), t + 150));
    t += 300 + Math.round(Math.random() * 120);
  }});
  _autoTimers.push(setTimeout(() => dots.classList.add('waiting'), t + 200));
}}

function previewReset() {{
  _autoTimers.splice(0).forEach(clearTimeout);
  document.querySelector('.pin-dots').classList.remove('waiting');
  document.querySelectorAll('.pin-key.auto-press').forEach(k => k.classList.remove('auto-press'));
  const lock = document.getElementById('pin-lock');
  _lockIntroTimers.splice(0).forEach(clearTimeout);
  lock.classList.add('no-anim', 'hidden');
  lock.classList.remove('staging', 'shot-in', 'shot-full');
  void lock.offsetWidth;
  lock.classList.remove('no-anim');
  _pin = ''; _pinDots();
}}
window.addEventListener('message', (e) => {{
  if (e.origin !== location.origin) return;
  if (e.data === 'ohlcv:play') previewPlay();
  else if (e.data === 'ohlcv:reset') previewReset();
  else if (e.data === 'ohlcv:autotype') previewAutotype();
}});
// Tell the home page when the intro has landed on the keypad, so it can
// cover the screen with the demo prompt. Watched from outside (the class
// finish() sets) rather than by changing the copied intro.
(function () {{
  const lock = document.getElementById('pin-lock');
  let told = false;
  new MutationObserver(() => {{
    const done = !lock.classList.contains('hidden') && !lock.classList.contains('staging')
      && lock.classList.contains('shot-full');
    if (done && !told && window.parent !== window) parent.postMessage('ohlcv:intro-done', location.origin);
    told = done;
  }}).observe(lock, {{ attributes: true, attributeFilter: ['class'] }});
}})();
// Opened on its own rather than inside the laptop: play straight away.
if (window.parent === window) previewPlay();
</script>
</body>
</html>
"""

if __name__ == "__main__":
    main()
